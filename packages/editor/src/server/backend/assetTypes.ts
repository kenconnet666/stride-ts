/**
 * 生成资源句柄（工程的 src/assets.gen.ts，见 docs/architecture.md 的"资源的强类型"）：内容目录里每个能在代码里引用的资源
 * 一个 `assetRef(种类, 路径)`，按种类、再按目录分层：
 *
 *   import { assets } from './assets.gen';
 *   const bullet = await game.content.load(assets.prefabs.Game.Prefabs.Bullet);
 *   await game.setRootScene(assets.scenes.Game.MainScene);
 *
 * 资源改名、删掉以后，引用它的代码在类型检查时报错。预制体的句柄带着它的结构（PrefabShape：有名字的根实体、子实体，每个
 * 实体上的脚本按导出名，脚本的类型 `import type` 自游戏的模块），`prefab.spawn` 的结果按它取：
 *
 *   const coin = (await game.content.load(assets.prefabs.Prefabs.Coin)).spawn(game.entities);
 *   coin.roots.Coin.scripts.Coin;                       // Coin 脚本，有类型
 *
 * 嵌套的预制体实例用那个预制体的根实体的结构。同名的兄弟实体只取第一个（同运行时）；没有名字的不进结构。模型的材质槽、
 * 场景里导出的实体还没有。同样的资源生成同样的文件（顺序固定），文件没变就不重写。
 */
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { scriptKey } from '@stride-ts/engine/content-prefabs';
import type { PrefabFile, SceneEntityFile } from '@stride-ts/engine/content-format';
import { parseJsonc } from '@stride-ts/engine/content-format';
import type { AssetRecord } from '../../shared/protocol.ts';

/**
 * 生成结构要的东西：预制体文件（按内容路径），脚本的 type 在哪个模块、导出名是什么（相对生成的文件的模块路径；找不到
 * 模块的，比如导入的 Stride 场景里的类型名，是 undefined，类型写 ScriptComponent）。
 */
export interface AssetStructures {
  readonly prefabs: ReadonlyMap<string, PrefabFile>;
  readonly scriptModule: (type: string) => { readonly module: string; readonly name: string } | undefined;
}

const NO_STRUCTURES: AssetStructures = { prefabs: new Map(), scriptModule: () => undefined };

/** 句柄的种类 → assets 下面的分组，也是生成的顺序。 */
const GROUPS: readonly (readonly [handle: string, group: string])[] = [
  ['scene', 'scenes'], ['prefab', 'prefabs'], ['model', 'models'], ['material', 'materials'], ['animation', 'animations'],
  ['spriteSheet', 'spriteSheets'], ['texture', 'textures'], ['font', 'fonts'], ['uiPage', 'uiPages'], ['uiLibrary', 'uiLibraries'],
  ['sound', 'sounds'],
];

interface Node {
  /** 这一层本身是个资源时，它的内容路径。 */
  asset?: string;
  readonly children: Map<string, Node>;
}

/** 生成文件的内容。content 是内容目录（写在文件头上，给人看的）。 */
export function generateAssetTypes(assets: readonly AssetRecord[], content: string, structures: AssetStructures = NO_STRUCTURES): string {
  const shapes = new PrefabShapes(structures);
  // 先给每个有文件的预制体起结构的名字（按路径排好，同样的资源同样的名字），嵌套的实例要引用别的预制体的
  for (const asset of [...assets].filter((a) => a.handle === 'prefab' && structures.prefabs.has(a.path)).sort((a, b) => (a.path < b.path ? -1 : 1))) shapes.name(asset.path);
  const lines: string[] = [];
  for (const [handle, group] of GROUPS) {
    const root: Node = { children: new Map() };
    for (const asset of assets) {
      if (asset.handle !== handle) continue;
      let node = root;
      for (const segment of asset.path.split('/')) {
        let child = node.children.get(segment);
        if (!child) node.children.set(segment, (child = { children: new Map() }));
        node = child;
      }
      node.asset = asset.path;
    }
    if (root.children.size === 0) continue;
    lines.push(`  ${group}: {`);
    emit(root, handle, 2, lines, shapes);
    lines.push('  },');
  }
  const declarations = shapes.declarations();
  return [
    `// Generated by @stride-ts/editor from the assets in ${content}. Do not edit; not committed (regenerated by the dev server`,
    '// and by `stride-editor assets-types`).',
    // 一个能引用的资源都没有时不导入引擎（没用到的导入过不了类型检查）
    ...(lines.length > 0 ? ["import { assetRef } from '@stride-ts/engine';", ''] : []),
    ...declarations,
    'export const assets = {',
    ...lines,
    '} as const;',
    '',
  ].join('\n');
}

function emit(node: Node, handle: string, depth: number, lines: string[], shapes: PrefabShapes): void {
  const indent = '  '.repeat(depth);
  for (const name of [...node.children.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))) {
    const child = node.children.get(name)!;
    const shape = child.asset !== undefined && handle === 'prefab' ? shapes.name(child.asset) : undefined;
    if (child.asset !== undefined) lines.push(`${indent}${key(name)}: assetRef${shape ? `<'prefab', ${shape}>` : ''}('${handle}', ${JSON.stringify(child.asset)}),`);
    if (child.children.size === 0) continue;
    // 同名的资源和目录（Models/Car 和 Models/Car/Wheel）：目录的键后面加一个斜杠
    lines.push(`${indent}${key(child.asset !== undefined ? `${name}/` : name)}: {`);
    emit(child, handle, depth + 1, lines, shapes);
    lines.push(`${indent}},`);
  }
}

const key = (name: string): string => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

/**
 * 预制体的结构类型：每个预制体一个 `PrefabN`（roots），每个实体一个 `PrefabN_M`（scripts、children），脚本的类型 `import type`
 * 进来（同一个导出只导一次，别名 `ScriptN`）。
 */
class PrefabShapes {
  readonly #structures: AssetStructures;
  readonly #names = new Map<string, string>();
  readonly #imports = new Map<string, { readonly alias: string; readonly module: string; readonly name: string }>();
  #engineScript = false;

  constructor(structures: AssetStructures) {
    this.#structures = structures;
  }

  /** 预制体的结构的名字；没有它的文件时是 undefined（句柄不带结构）。 */
  name(prefabPath: string): string | undefined {
    if (!this.#structures.prefabs.has(prefabPath)) return undefined;
    let name = this.#names.get(prefabPath);
    if (name === undefined) this.#names.set(prefabPath, (name = `Prefab${this.#names.size}`));
    return name;
  }

  declarations(): string[] {
    const body: string[] = [];
    for (const [prefabPath, name] of this.#names) body.push(...this.#prefab(prefabPath, name));
    if (body.length === 0) return [];
    const imports = [...this.#imports.values()].map(({ alias, module, name }) => `import type { ${name === alias ? name : `${name} as ${alias}`} } from '${module}';`);
    return [...(this.#engineScript ? ["import type { ScriptComponent } from '@stride-ts/engine';"] : []), ...imports, '', ...body];
  }

  /** 一个预制体的结构：根实体按名字（同名取第一个），每个实体一个接口。 */
  #prefab(prefabPath: string, name: string): string[] {
    const file = this.#structures.prefabs.get(prefabPath)!;
    const lines: string[] = [];
    const children = new Map<string | null, SceneEntityFile[]>();
    const ids = new Set(file.entities.map((entity) => entity.id));
    for (const entity of file.entities) {
      const parent = entity.parent !== null && ids.has(entity.parent) ? entity.parent : null;
      children.set(parent, [...(children.get(parent) ?? []), entity]);
    }
    const entityName = (entity: SceneEntityFile) => `${name}_${file.entities.indexOf(entity)}`;
    const members = (list: readonly SceneEntityFile[]) => {
      const seen = new Set<string>();
      return list.filter((entity) => entity.name !== '' && !seen.has(entity.name) && seen.add(entity.name));
    };
    // 只写从有名字的根往下够得着的实体（同名的、没名字的不进结构，接口写了也没人用）
    const entityLines: string[] = [];
    const shapeOf = (entity: SceneEntityFile): string => {
      // 嵌套的预制体实例：那个预制体只有一个根时用它的根的结构
      if (entity.prefab) {
        const nested = this.name(entity.prefab.path);
        const roots = nested ? (this.#structures.prefabs.get(entity.prefab.path)?.entities ?? []).filter((e) => e.parent === null) : [];
        return nested && roots.length === 1 && roots[0]!.name !== '' ? `${nested}['roots'][${JSON.stringify(roots[0]!.name)}]` : '{ readonly scripts: {}; readonly children: {} }';
      }
      const scripts = new Map<string, string>();
      for (const { type } of entity.components.scripts ?? []) {
        const scriptName = scriptKey(type);
        if (!scripts.has(scriptName)) scripts.set(scriptName, this.#scriptType(type));
      }
      const own = members(children.get(entity.id) ?? []).map((child) => ` readonly ${key(child.name)}: ${shapeOf(child)};`);
      entityLines.push(
        `interface ${entityName(entity)} {`,
        `  readonly scripts: {${[...scripts].map(([script, type]) => ` readonly ${key(script)}: ${type};`).join('')}${scripts.size > 0 ? ' ' : ''}};`,
        `  readonly children: {${own.join('')}${own.length > 0 ? ' ' : ''}};`,
        '}',
      );
      return entityName(entity);
    };
    lines.push(`/** ${prefabPath} */`, `interface ${name} {`, `  readonly roots: {`);
    for (const root of members(children.get(null) ?? [])) lines.push(`    readonly ${key(root.name)}: ${shapeOf(root)};`);
    lines.push('  };', '}', ...entityLines);
    lines.push('');
    return lines;
  }

  /** 脚本的类型：找得到模块的 `import type`，找不到的 ScriptComponent。 */
  #scriptType(type: string): string {
    const found = this.#structures.scriptModule(type);
    if (!found) {
      this.#engineScript = true;
      return 'ScriptComponent';
    }
    const id = `${found.module}#${found.name}`;
    let entry = this.#imports.get(id);
    if (!entry) {
      const taken = new Set([...this.#imports.values()].map((value) => value.alias));
      const alias = taken.has(found.name) || found.name === 'ScriptComponent' || found.name === 'assetRef' ? `Script${this.#imports.size}` : found.name;
      this.#imports.set(id, (entry = { alias, module: found.module, name: found.name }));
    }
    return entry.alias;
  }
}

/**
 * 把生成的内容写到 file；和现有的一样时不写（不惊动监视文件的开发服务器），返回写了没有。工程里没有能引用的资源、
 * 文件也还不存在时不建它（不用内容目录的应用里不多出一个空文件）。
 */
export async function writeAssetTypes(file: string, assets: readonly AssetRecord[], content: string, contentDir?: string): Promise<boolean> {
  const text = generateAssetTypes(assets, content, contentDir === undefined ? NO_STRUCTURES : await readStructures(file, assets, contentDir));
  const existing = await readFile(file, 'utf8').catch(() => undefined);
  if (existing === text || (existing === undefined && !assets.some((asset) => asset.handle !== undefined))) return false;
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, text);
  return true;
}

/**
 * 读生成结构要的文件：预制体文件（读不了、写坏了的跳过：句柄不带结构），脚本的模块按登记的名字（`路径#导出名`，路径相对
 * 游戏的模块目录，就是生成的文件所在的目录）找 .ts、.tsx。
 */
async function readStructures(file: string, assets: readonly AssetRecord[], contentDir: string): Promise<AssetStructures> {
  const prefabs = new Map<string, PrefabFile>();
  for (const asset of assets) {
    if (asset.handle !== 'prefab' || asset.files[0] === undefined) continue;
    try {
      prefabs.set(asset.path, parseJsonc(await readFile(path.join(contentDir, asset.files[0]!), 'utf8'), asset.files[0]) as PrefabFile);
    } catch {
      // 写坏了的预制体：数据库会报，句柄照常生成，只是不带结构
    }
  }
  const directory = path.dirname(file);
  const modules = new Map<string, boolean>();
  const scriptModule = (type: string) => {
    const hash = type.lastIndexOf('#');
    if (hash <= 0) return undefined;
    const module = type.slice(0, hash);
    let exists = modules.get(module);
    if (exists === undefined) modules.set(module, (exists = ['.ts', '.tsx'].some((extension) => existsSync(path.join(directory, module + extension)))));
    return exists ? { module: `./${module}`, name: type.slice(hash + 1) } : undefined;
  };
  return { prefabs, scriptModule };
}
